func TestAssignmentEncodingEveryField(t *testing.T) {
	e, target, q, p, records := encodingFixtures(t)
	// Each alternative changes one field, except where an A1a invariant requires
	// linked fields to change together (subject, revision and claim support).
	evidenceVariants := []Evidence{e, e, e, e, e}
	evidenceVariants[0].id = evidenceID(t, 2)
	evidenceVariants[1].subject = reviewTag(t, 2)
	evidenceVariants[2].kind = ImportedAssertion
	evidenceVariants[3].source += " "
	evidenceVariants[4].disposition = PendingEvidence
	targetVariants := []OriginalTarget{baselineTarget(t, 2, 1), baselineTarget(t, 1, 2)}
	requestVariants := []ReviewRequest{q, q, q, q}
	requestVariants[0].command = reviewRequest(t, 2, 0).command
	requestVariants[1].expectedRevision++
	requestVariants[2].policyRevision++
	requestVariants[3].reason += " "
	provenanceVariants := []ReviewProvenance{p, p, p, p, p, p}
	provenanceVariants[0].Command = reviewRequest(t, 2, 0).command
	provenanceVariants[1].Subject = reviewTag(t, 2)
	provenanceVariants[2].Actor += " "
	provenanceVariants[3].Reason += " "
	provenanceVariants[4].PolicyRevision++
	provenanceVariants[5].ExpectedRevision++
	provenanceVariants[5].Revision++
	check := func(name string, base encodedReviewValue, alternatives []encodedReviewValue) {
		t.Helper()
		original := checkedCanonical(t, base)
		seen := map[string]bool{string(original): true}
		for i, v := range alternatives {
			b := checkedCanonical(t, v)
			if seen[string(b)] {
				t.Fatalf("%s field %d lost or collided", name, i)
			}
			seen[string(b)] = true
		}
	}
	var variants []encodedReviewValue
	for _, v := range evidenceVariants {
		variants = append(variants, v)
	}
	check("Evidence", e, variants)
	variants = nil
	for _, v := range targetVariants {
		variants = append(variants, v)
	}
	check("OriginalTarget", target, variants)
	variants = nil
	for _, v := range requestVariants {
		variants = append(variants, v)
	}
	check("ReviewRequest", q, variants)
	variants = nil
	for _, v := range provenanceVariants {
		variants = append(variants, v)
	}
	check("ReviewProvenance", p, variants)
	// Embedded primitive changes must also change the complete record bytes.
	for _, base := range records {
		variants = nil
		for _, v := range provenanceVariants {
			r := base
			r.Provenance = v
			if r.Kind == ClassificationClaim || r.Kind == OriginalTargetClaim {
				r.Evidence.subject = v.Subject
			}
			variants = append(variants, r)
		}
		if base.Kind == ClassificationClaim || base.Kind == OriginalTargetClaim {
			for i, v := range evidenceVariants {
				// The coupled subject change was already tested via provenance.
				if i == 1 {
					continue
				}
				r := base
				r.Evidence, r.Provenance.Subject, r.Support = v, v.subject, []EvidenceID{v.id}
				variants = append(variants, r)
			}
		} else {
			r := base
			r.Support = []EvidenceID{e.id}
			variants = append(variants, r)
			r.Support = []EvidenceID{e.id, evidenceID(t, 3)}
			variants = append(variants, r)
		}
		if base.Kind == ClassificationClaim || base.Kind == ClassificationResolution {
			r := base
			r.Classification = CustomCard
			variants = append(variants, r)
		} else {
			for _, v := range targetVariants {
				r := base
				r.Target = v
				variants = append(variants, r)
			}
		}
		check("ReviewRecord", base, variants)
	}
	// All four discriminators and all five top-level types are distinct.
	check("kind", records[0], []encodedReviewValue{records[1], records[2], records[3]})
	check("type", e, []encodedReviewValue{target, q, p, records[0]})
	// Framing prevents field-boundary ambiguity; text is never normalized.
	a, b := p, p
	a.Actor, a.Reason, b.Actor, b.Reason = "ab", "c", "a", "bc"
	check("text framing", a, []encodedReviewValue{b})
}

func TestAssignmentEncodingGoldenRejectedSupport(t *testing.T) {
	_, _, _, _, records := encodingFixtures(t)
	// Neither representation has canonical bytes. These are literal rejection
	// vectors for every record kind, not a nil-to-empty normalization rule.
	for _, r := range records {
		for _, support := range [][]EvidenceID{nil, {}} {
			r.Support = support
			b, err := r.CanonicalBytes()
			if b != nil || err != ErrInvalidCanonicalValue {
				t.Fatalf("kind %d, support %#v: got %x, %v", r.Kind, support, b, err)
			}
			n, err := r.CanonicalByteLen()
			if n != 0 || err != ErrInvalidCanonicalValue {
				t.Fatalf("kind %d, support %#v: got length %d, %v", r.Kind, support, n, err)
			}
		}
	}
}

func TestAssignmentEncodingRejectsInvalidValues(t *testing.T) {
	e, target, q, p, records := encodingFixtures(t)
	bad := []encodedReviewValue{Evidence{}, OriginalTarget{}, ReviewRequest{}, ReviewProvenance{}, ReviewRecord{}}
	for _, id := range []EvidenceID{{}, {value: "evd_" + strings.Repeat("I", 26)}, {value: "rev_" + strings.Repeat("0", 26)}} {
		v := e
		v.id = id
		bad = append(bad, v)
	}
	v := e
	v.subject = identity.TagID{}
	bad = append(bad, v)
	for _, kind := range []EvidenceKind{0, 3, 255} {
		v := e
		v.kind = kind
		bad = append(bad, v)
	}
	for _, d := range []EvidenceDisposition{0, 5, 255} {
		v := e
		v.disposition = d
		bad = append(bad, v)
	}
	for _, text := range []string{"", " ", "x\n", "x\x7f", string([]byte{0xff}), strings.Repeat("a", MaxReviewReferenceBytes+1)} {
		v := e
		v.source = text
		bad = append(bad, v)
		v2 := p
		v2.Actor = text
		bad = append(bad, v2)
	}
	for _, reason := range []string{"", " ", "x\u0085", string([]byte{0xff}), strings.Repeat("é", MaxReviewReasonBytes/2) + "x"} {
		v := q
		v.reason = reason
		bad = append(bad, v)
		v2 := p
		v2.Reason = reason
		bad = append(bad, v2)
	}
	for _, id := range []ReviewID{{}, {value: "rev_" + strings.Repeat("I", 26)}} {
		v := q
		v.command = id
		bad = append(bad, v)
		v2 := p
		v2.Command = id
		bad = append(bad, v2)
	}
	vq := q
	vq.policyRevision = 0
	bad = append(bad, vq)
	vp := p
	vp.PolicyRevision = 0
	bad = append(bad, vp)
	vp = p
	vp.Subject = identity.TagID{}
	bad = append(bad, vp)
	for _, revision := range []uint64{0, 2, ^uint64(0)} {
		vp := p
		vp.Revision = revision
		bad = append(bad, vp)
	}
	vp = p
	vp.ExpectedRevision, vp.Revision = ^uint64(0), 0
	bad = append(bad, vp)
	vp = p
	vp.ExpectedRevision = 1
	bad = append(bad, vp)
	vt := target
	vt.content = identity.ContentID{}
	bad = append(bad, vt)
	vt = target
	vt.version = identity.ContentVersionID{}
	bad = append(bad, vt)
	for _, base := range records {
		// Nil/empty have explicit rejection vectors, rather than normalization.
		for _, support := range [][]EvidenceID{nil, {}, {{}}, {e.id, e.id}, make([]EvidenceID, MaxSelectedSupport+1), {{value: "evd_" + strings.Repeat("I", 26)}}} {
			r := base
			r.Support = support
			bad = append(bad, r)
		}
		r := base
		r.Kind = 0
		bad = append(bad, r)
		r = base
		r.Kind = 255
		bad = append(bad, r)
		r = base
		r.Provenance.Actor = ""
		bad = append(bad, r)
		if base.Kind == ClassificationClaim || base.Kind == OriginalTargetClaim {
			r := base
			r.Evidence.subject = reviewTag(t, 2)
			bad = append(bad, r)
			r = base
			r.Evidence = Evidence{}
			bad = append(bad, r)
			r = base
			r.Support = []EvidenceID{evidenceID(t, 2)}
			bad = append(bad, r)
			r = base
			r.Support = []EvidenceID{e.id, evidenceID(t, 2)}
			bad = append(bad, r)
		} else {
			// Inactive payload, even a partial payload, must never be ignored.
			r := base
			r.Evidence = e
			bad = append(bad, r)
			r = base
			r.Evidence.source = "hidden"
			bad = append(bad, r)
		}
		if base.Kind == ClassificationClaim || base.Kind == ClassificationResolution {
			for _, c := range []PhysicalClassification{Unknown, Conflict, 255} {
				r := base
				r.Classification = c
				bad = append(bad, r)
			}
			r := base
			r.Target = target
			bad = append(bad, r)
			r = base
			r.Target.content = target.content
			bad = append(bad, r)
		} else {
			r := base
			r.Classification = Original
			bad = append(bad, r)
			r = base
			r.Target = OriginalTarget{}
			bad = append(bad, r)
			r = base
			r.Target.version = identity.ContentVersionID{}
			bad = append(bad, r)
		}
	}
	for i, v := range bad {
		b, err := v.CanonicalBytes()
		if err != ErrInvalidCanonicalValue || b != nil {
			t.Fatalf("invalid vector %d (%T) encoded %x: %v", i, v, b, err)
		}
		n, err := v.CanonicalByteLen()
		if err != ErrInvalidCanonicalValue || n != 0 {
			t.Fatalf("invalid vector %d measured %d: %v", i, n, err)
		}
	}
}

func TestAssignmentEncodingBoundsAndEnvelope(t *testing.T) {
	e, _, q, p, records := encodingFixtures(t)
	// A1a permits all uint64 request revisions. Encoding does not silently clamp
	// these values to the later decision ledger's signed-64 admission ceiling.
	q.expectedRevision, q.policyRevision = ^uint64(0), ^uint64(0)
	checkedCanonical(t, q)
	p.ExpectedRevision, p.Revision, p.PolicyRevision = ^uint64(0)-1, ^uint64(0), ^uint64(0)
	checkedCanonical(t, p)
	for _, d := range []EvidenceDisposition{PendingEvidence, DisputedEvidence, RejectedEvidence, AcceptedEvidence} {
		e.disposition = d
		checkedCanonical(t, e)
	}
	for _, r := range records {
		r.Provenance.Actor = strings.Repeat("é", MaxReviewReferenceBytes/2)
		r.Provenance.Reason = strings.Repeat("é", MaxReviewReasonBytes/2)
		if r.Kind == ClassificationClaim || r.Kind == OriginalTargetClaim {
			r.Evidence.source = strings.Repeat("é", MaxReviewReferenceBytes/2)
		} else {
			r.Support = make([]EvidenceID, MaxSelectedSupport)
			for i := range r.Support {
				r.Support[i] = evidenceID(t, len(r.Support)-i)
			}
		}
		before := append([]EvidenceID(nil), r.Support...)
		b := checkedCanonical(t, r)
		if !reflect.DeepEqual(before, r.Support) {
			t.Fatal("support mutated")
		}
		// Existing A1a envelope is preserved; this is a primitive byte check,
		// not a claim of complete future command/result/index accounting.
		if uint64(len(b)) > reviewRetention(r) {
			t.Fatal("canonical primitive exceeds A1a envelope")
		}
	}
}

func TestAssignmentEncodingA1aRecords(t *testing.T) {
	s := emptyEvidence(t)
	s = addClassification(t, s, 1, AcceptedEvidence, Original)
	s = addClassification(t, s, 2, AcceptedEvidence, CustomCard)
	var err error
	s, err = s.ResolveClassification(reviewCore(t), reviewRequest(t, 3, 2), Original, []EvidenceID{evidenceID(t, 1)})
	if err != nil {
		t.Fatal(err)
	}
	target := baselineTarget(t, 1, 1)
	s = addBaseline(t, s, 3, AcceptedEvidence, target)
	s = addBaseline(t, s, 4, AcceptedEvidence, baselineTarget(t, 1, 2))
	s, err = s.ResolveOriginalTarget(reviewCore(t), reviewRequest(t, 6, 5), target, []EvidenceID{evidenceID(t, 3)})
	if err != nil {
		t.Fatal(err)
	}
	before := s.Records()
	var total uint64
	for _, r := range before {
		total += uint64(len(checkedCanonical(t, r)))
	}
	if total > s.Usage().RetainedBytes() || !reflect.DeepEqual(before, s.Records()) {
		t.Fatal("primitive encoding exceeds charged envelope or mutated history")
	}
}
