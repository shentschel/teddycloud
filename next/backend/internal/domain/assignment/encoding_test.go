type encodedReviewValue interface {
	CanonicalBytes() ([]byte, error)
	CanonicalByteLen() (uint64, error)
}

func encodingFixtures(t *testing.T) (Evidence, OriginalTarget, ReviewRequest, ReviewProvenance, []ReviewRecord) {
	t.Helper()
	e := claimEvidence(t, reviewTag(t, 1), 1, AcceptedEvidence)
	e.source = "src"
	target := baselineTarget(t, 1, 1)
	q := reviewRequest(t, 1, 0x0102030405060708)
	q.policyRevision, q.reason = 0x1112131415161718, "why"
	p := ReviewProvenance{q.command, e.subject, "actor", "why", 7, 0, 1}
	records := []ReviewRecord{
		{Kind: ClassificationClaim, Provenance: p, Evidence: e, Classification: Original, Support: []EvidenceID{e.id}},
		{Kind: OriginalTargetClaim, Provenance: p, Evidence: e, Target: target, Support: []EvidenceID{e.id}},
		{Kind: ClassificationResolution, Provenance: p, Classification: Original, Support: []EvidenceID{e.id, evidenceID(t, 2)}},
		{Kind: OriginalTargetResolution, Provenance: p, Target: target, Support: []EvidenceID{e.id, evidenceID(t, 2)}},
	}
	return e, target, q, p, records
}

func checkedCanonical(t *testing.T, v encodedReviewValue) []byte {
	t.Helper()
	b, err := v.CanonicalBytes()
	if err != nil {
		t.Fatal(err)
	}
	n, err := v.CanonicalByteLen()
	if err != nil || n != uint64(len(b)) {
		t.Fatalf("length %d != %d: %v", n, len(b), err)
	}
	return b
}

