func TestLibraryCursorBindingCodec(t *testing.T) {
	var secret, snapshot, digest [32]byte
	for i := range secret {
		secret[i] = byte(i)
		snapshot[i] = byte(i + 32)
		digest[i] = byte(i + 64)
	}
	content := "cnt_00000000000000000000000001"
	version := "ver_00000000000000000000000002"
	token := libraryEncodeCursor(secret, snapshot, digest, content, version)
	const golden = "ASAhIiMkJSYnKCkqKywtLi8wMTIzNDU2Nzg5Ojs8PT4_Y250XzAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAxdmVyXzAwMDAwMDAwMDAwMDAwMDAwMDAwMDAwMDAyQEFCQ0RFRkdISUpLTE1OT1BRUlNUVVZXWFlaW1xdXl90S0hRIPYqeccTPVZPSkAvOoPTvmze-1a9dg_Uy3l0HQ"
	if token != golden || len(token) != 210 {
		t.Fatal(token)
	}
	got, err := libraryDecodeCursor(golden, secret, digest)
	if err != nil || got.snapshot != snapshot || got.content != content || got.version != version {
		t.Fatal(got, err)
	}
	for _, bad := range []string{token + "=", token[:209], strings.Repeat("A", 256), "v1-catalog-history", strings.Repeat("A", 210), token[:209] + "B"} {
		if _, err := libraryDecodeCursor(bad, secret, digest); err != lib.ErrStaleCursor {
			t.Fatal(bad, err)
		}
	}
	if _, err := libraryDecodeCursor(strings.Repeat("A", 257), secret, digest); err != lib.ErrLimitExceeded {
		t.Fatal(err)
	}
	// Authenticated invalid version/extension/identity fail closed as well.
	raw, _ := base64.RawURLEncoding.DecodeString(token)
	for _, at := range []int{0, 33, 63} {
		bad := append([]byte(nil), raw[:125]...)
		bad[at] = '!'
		mac := hmac.New(sha256.New, secret[:])
		mac.Write([]byte(libraryCursorDomain))
		mac.Write(bad)
		bad = mac.Sum(bad)
		if _, err := libraryDecodeCursor(base64.RawURLEncoding.EncodeToString(bad), secret, digest); err != lib.ErrStaleCursor {
			t.Fatal(at, err)
		}
	}
}
func TestLibraryCursorBinding(t *testing.T) {
	o := catalogQueryOwner(t)
	s := lib.NewService(o)
	scope := o.LibraryReadScope()
	libraryUnmanaged(t, o, 1, 1, 4, "baseline")
	libraryReady(t, o, s, scope)
	p := lib.Page{Limit: 1}
	first, err := s.ListLibrary(t.Context(), lib.Query{}, p, scope)
	if err != nil {
		t.Fatal(err)
	}
	p.Cursor = first.Next
	p.ExpectedSnapshot = first.Snapshot
	second, err := s.ListLibrary(t.Context(), lib.Query{}, p, scope)
	if err != nil {
		t.Fatal(err)
	}
	again, err := s.ListLibrary(t.Context(), lib.Query{Versions: lib.All, Sort: lib.IdentityAsc}, p, scope)
	if err != nil || !reflect.DeepEqual(second, again) {
		t.Fatal("canonical replay", again, err)
	}
	before := catalogRecoveryRows(t, o.database.db)
	for _, tc := range []struct {
		name  string
		p     lib.Page
		scope lib.ReadScope
		want  error
	}{
		{"missing-snapshot", lib.Page{Limit: 1, Cursor: first.Next}, scope, lib.ErrInvalidInput},
		{"changed-limit", lib.Page{Limit: 2, Cursor: first.Next, ExpectedSnapshot: first.Snapshot}, scope, lib.ErrStaleCursor},
		{"different-snapshot", lib.Page{Limit: 1, Cursor: first.Next, ExpectedSnapshot: strings.Repeat("A", 43)}, scope, lib.ErrStaleCursor},
		{"different-scope", p, o.LibraryReadScope(), lib.ErrStaleCursor},
		{"forged", lib.Page{Limit: 1, Cursor: strings.Repeat("A", 210), ExpectedSnapshot: first.Snapshot}, scope, lib.ErrStaleCursor},
		{"256", lib.Page{Limit: 1, Cursor: strings.Repeat("A", 256), ExpectedSnapshot: first.Snapshot}, scope, lib.ErrStaleCursor},
		{"257", lib.Page{Limit: 1, Cursor: strings.Repeat("A", 257), ExpectedSnapshot: first.Snapshot}, scope, lib.ErrLimitExceeded},
	} {
		t.Run(tc.name, func(t *testing.T) {
			r, err := s.ListLibrary(t.Context(), lib.Query{}, tc.p, tc.scope)
			if err != tc.want || r.Next != "" || len(r.Items) != 0 {
				t.Fatal(r, err)
			}
		})
	}
	pinned, err := s.ListLibrary(t.Context(), lib.Query{}, lib.Page{Limit: 1, ExpectedSnapshot: first.Snapshot}, scope)
	if err != nil || !reflect.DeepEqual(first, pinned) {
		t.Fatal("pinned first", err)
	}
	// Exercise otherwise-valid B options through the actual authorized service.
	id := catalogQueryContent(t, 1)
	search := "baseline"
	for _, q := range []lib.Query{{OwnerContentID: &id}, {Versions: lib.Current}, {Sort: lib.TitleAsc}, {Sort: lib.TitleDesc}, {Search: &search, Sort: lib.TitleAsc}} {
		if _, err := s.ListLibrary(t.Context(), q, p, scope); err != lib.ErrStaleCursor {
			t.Fatal(q, err)
		}
	}
	if _, err := s.ListLibrary(t.Context(), lib.Query{Search: &search}, p, scope); err != lib.ErrUnsupported {
		t.Fatal(err)
	}
	// Existing PI-08 token, generated by its real protocol, is foreign.
	old, err := catalogRead(t, o, catalog.Query{Kind: catalog.ListVersions, Content: catalogQueryContent(t, 1), Page: catalog.PageRequest{Limit: 1}})
	if err != nil {
		t.Fatal(err)
	}
	foreign := p
	foreign.Cursor = old.Next
	if _, err := s.ListLibrary(t.Context(), lib.Query{}, foreign, scope); err != lib.ErrStaleCursor {
		t.Fatal(err)
	}
	// Query/scope digest's exact field encoding is independently reconstructed.
	q, _ := lib.NormalizeQuery(lib.Query{}, p)
	digest := libraryQueryDigest(q, p, scope, o.library.incarnation)
	if hex.EncodeToString(digest[:]) == "" {
		t.Fatal("digest")
	}
	for _, mutation := range []func() [32]byte{
		func() [32]byte {
			q.Sort = lib.TitleAsc
			defer func() { q.Sort = lib.IdentityAsc }()
			return libraryQueryDigest(q, p, scope, o.library.incarnation)
		},
		func() [32]byte {
			other := o.library.incarnation
			other[0] ^= 1
			return libraryQueryDigest(q, p, scope, other)
		},
	} {
		if mutation() == digest {
			t.Fatal("binding field ignored")
		}
	}
	// MAC-valid token referencing an absent last identity must still be stale.
	missing := p
	missing.Cursor = libraryEncodeCursor(o.library.secret, o.library.snapshot, digest, catalogSchemaID("cnt", 1), catalogSchemaID("ver", 99))
	if _, err := s.ListLibrary(t.Context(), lib.Query{}, missing, scope); err != lib.ErrStaleCursor {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, catalogRecoveryRows(t, o.database.db)) {
		t.Fatal("cursor failure changed source")
	}
}

func TestLibraryCursorBindingDigestGolden(t *testing.T) {
	var scope, incarnation [32]byte
	for i := range scope {
		scope[i] = byte(i)
		incarnation[i] = byte(255 - i)
	}
	q := lib.Query{Versions: lib.All, Sort: lib.IdentityAsc}
	sum := libraryDigest(lib.Profile, q, 16, scope, 7, incarnation)
	const golden = "77273d9e5b61d30c7bb14d9d71bf1da7f7afbae4c00fe203c4152689fce6072c"
	if hex.EncodeToString(sum[:]) != golden {
		t.Fatal(hex.EncodeToString(sum[:]))
	}
	if libraryDigest("pi10-library/2", q, 16, scope, 7, incarnation) == sum || libraryDigest(lib.Profile, q, 16, scope, 8, incarnation) == sum {
		t.Fatal("profile/generation binding omitted")
	}
	for _, change := range []lib.Query{{Versions: lib.Current, Sort: lib.IdentityAsc}, {Versions: lib.All, Sort: lib.TitleAsc}, {OwnerContentID: func() *identity.ContentID { id := catalogQueryContent(t, 1); return &id }(), Versions: lib.All, Sort: lib.IdentityAsc}, {Versions: lib.All, Sort: lib.IdentityAsc, Search: func() *string { s := "prefix"; return &s }()}} {
		if libraryDigest(lib.Profile, change, 16, scope, 7, incarnation) == sum {
			t.Fatal(change)
		}
	}
}

func TestLibraryCursorBindingDifferentDatabase(t *testing.T) {
	owners := []*LifecycleOwner{catalogQueryOwner(t), catalogQueryOwner(t)}
	var services []*lib.Service
	var scopes []lib.ReadScope
	for _, o := range owners {
		libraryUnmanaged(t, o, 1, 1, 2, "")
		s := lib.NewService(o)
		scope := o.LibraryReadScope()
		libraryReady(t, o, s, scope)
		services = append(services, s)
		scopes = append(scopes, scope)
	}
	first, err := services[0].ListLibrary(t.Context(), lib.Query{}, lib.Page{Limit: 1}, scopes[0])
	if err != nil {
		t.Fatal(err)
	}
	if _, err := services[1].ListLibrary(t.Context(), lib.Query{}, lib.Page{Limit: 1, Cursor: first.Next, ExpectedSnapshot: first.Snapshot}, scopes[1]); err != lib.ErrStaleCursor {
		t.Fatal(err)
	}
	if _, err := services[1].ListLibrary(t.Context(), lib.Query{}, lib.Page{Limit: 1}, scopes[0]); err != lib.ErrUnauthorized {
		t.Fatal("foreign grant", err)
	}
}

